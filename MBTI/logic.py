def cosine_similarity(v1, v2):
    """
    두 벡터 v1과 v2 사이의 코사인 유사도를 계산합니다.
    분모가 0인 경우 0.0을 리턴하여 안전하게 설계되었습니다.
    """
    dot_product = sum(a * b for a, b in zip(v1, v2))
    norm_v1 = math.sqrt(sum(a * a for a in v1))
    norm_v2 = math.sqrt(sum(b * b for b in v2))
    if norm_v1 == 0 or norm_v2 == 0:
        return 0.0
    return dot_product / (norm_v1 * norm_v2)

def calculate_scores(answers):
    """
    사용자의 20문항 답변 리스트(0 또는 1)를 기반으로 5대 역량의 최종 가중 합산 점수를 구합니다.
    """
    scores = {
        "communication": 0.0,
        "strategy": 0.0,
        "coordination": 0.0,
        "sourcing": 0.0,
        "compliance": 0.0
    }
    
    for i, ans_idx in enumerate(answers):
        if ans_idx is None:
            continue
        q = QUESTIONS[i]
        selected_option = q["options"][ans_idx]
        for axis, val in selected_option["scores"].items():
            scores[axis] += val
            
    return scores

def find_best_matching_persona(scores):
    """
    사용자의 5대 역량 점수를 기반으로 6가지 페르소나 중 가장 코사인 유사도가 높은 직무 성향을 찾아 매칭합니다.
    """
    # 5대 역량 값의 순서를 정확히 맞춘 사용자 벡터 생성
    v_user = [
        scores.get("communication", 0.0),
        scores.get("strategy", 0.0),
        scores.get("coordination", 0.0),
        scores.get("sourcing", 0.0),
        scores.get("compliance", 0.0)
    ]
    
    best_persona_key = None
    best_similarity = -1.0
    similarities = {}
    
    for key, p_data in PERSONAS.items():
        v_p = p_data["vector"]
        sim = cosine_similarity(v_user, v_p)
        similarities[key] = sim
        if sim > best_similarity:
            best_similarity = sim
            best_persona_key = key
            
    return best_persona_key, best_similarity, similarities
